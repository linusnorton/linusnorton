const UNKNOWN = "?";

/** Characters a board can actually display, for anything that wants to check before it draws */
export function charset(): string[] {
  return Object.keys(GLYPHS);
}

/**
 * Fold text down to what the matrix can show: uppercase, with the accented characters that turn up
 * in station and operator names flattened rather than replaced by a question mark, since "Bekesbourne"
 * reads better than "Bek?sbourne".
 */
export function normalise(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[‐-―]/g, "-")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/•/g, "·")
    .toUpperCase()
    .split("")
    .map(char => (char in GLYPHS ? char : UNKNOWN))
    .join("");
}

/** The lit dots of a single character, as [column, row] pairs within a 5x7 cell */
export function litDots(char: string): Array<[number, number]> {
  const columns = GLYPHS[char] ?? GLYPHS[UNKNOWN]!;
  const dots: Array<[number, number]> = [];

  for (let column = 0; column < GLYPH_COLUMNS; column++) {
    for (let row = 0; row < GLYPH_ROWS; row++) {
      if ((columns[column]! >> row) & 1) {
        dots.push([column, row]);
      }
    }
  }

  return dots;
}
